/**
 * The icon for a command in the `/` menu. A command written as a file in the person's or
 * project's folders is a file; one with no icon of its own yet shows the slash.
 */
export function commandIcon(name: string, source?: "builtin" | "user" | "project"): LucideIcon {
  const known = byName[name.toLowerCase()];
  if (known) return known;
  if (source === "user" || source === "project") return FileCode;
  if (name.startsWith("prompts:")) return FileText;
  return SquareSlash;
}
