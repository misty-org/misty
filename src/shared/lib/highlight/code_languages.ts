export function codeLanguage(language: string | undefined): string | undefined {
  const id = language?.toLowerCase();
  if (!id) return undefined;
  const known = Object.hasOwn(aliases, id) ? aliases[id] : id;
  return Object.hasOwn(grammars, known) ? known : undefined;
}

export const codeGrammar = (id: string): LanguageInput => grammars[id];
