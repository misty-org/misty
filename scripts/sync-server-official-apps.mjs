import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const appsRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const targetPath = path.resolve(
  process.argv[2] ??
    path.join(appsRoot, "../misty-server/internal/appcatalog/catalog.go"),
);
const catalogPath = path.resolve(
  process.argv[3] ?? path.join(appsRoot, "apps/catalog.json"),
);
const catalogText = await readFile(catalogPath, "utf8");
const catalog = JSON.parse(catalogText);

const generated = `// Code generated by misty-apps/scripts/sync-server-official-apps.mjs; DO NOT EDIT.

package appcatalog

import (
\t"encoding/json"
\t"crypto/sha256"
\t"fmt"
\t"strings"
)

const HostProtocolVersion = ${catalog.host_protocol_version}

type Runtime string

const (
\tRuntimeDownloaded Runtime = "downloaded"
\tRuntimeHosted Runtime = "hosted"
\tRuntimeEmbedded Runtime = "embedded"
\tRuntimeUnsupported Runtime = "unsupported"
)

type PlatformRuntime struct {
\tRuntime Runtime \`json:"runtime"\`
\tEntry string \`json:"entry,omitempty"\`
\tSHA256 string \`json:"sha256,omitempty"\`
\tStyleSHA256 string \`json:"style_sha256,omitempty"\`
\tSignature string \`json:"signature,omitempty"\`
\tSignatureKeyID string \`json:"signature_key_id,omitempty"\`
\tDownloadBytes int64 \`json:"download_bytes,omitempty"\`
\tAdditionalStorageBytes int64 \`json:"additional_storage_bytes,omitempty"\`
}

type App struct {
\tID string \`json:"id"\`
\tAppID string \`json:"app_id,omitempty"\`
\tSlug string \`json:"slug,omitempty"\`
\tName string \`json:"name"\`
\tPublisher string \`json:"publisher"\`
\tDescription string \`json:"description"\`
\tVersion string \`json:"version"\`
\tPermissionVersion int \`json:"permission_version"\`
\tMinimumHost int \`json:"minimum_host_protocol"\`
\tMinimumHostVersion string \`json:"minimum_host_version,omitempty"\`
\tOfficial bool \`json:"official"\`
\tAgeRating string \`json:"age_rating"\`
\tScopes []string \`json:"scopes"\`
\tDesktop PlatformRuntime \`json:"desktop"\`
\tMobile PlatformRuntime \`json:"mobile"\`
}

type catalogDocument struct {
\tApps []App \`json:"apps"\`
}

const generatedCatalog = \`${catalogText.trim()}\`

var officialApps = mustCatalogApps()

func mustCatalogApps() []App {
\tvar document catalogDocument
\tif err := json.Unmarshal([]byte(generatedCatalog), &document); err != nil {
\t\tpanic("invalid generated official app catalog: " + err.Error())
\t}
\treturn document.Apps
}

func Digest() string { return fmt.Sprintf("%x", sha256.Sum256([]byte(strings.TrimSpace(generatedCatalog)))) }

func All() []App {
\tresult := make([]App, len(officialApps))
\tcopy(result, officialApps)
\tfor index := range result {
\t\tresult[index].Scopes = append([]string(nil), result[index].Scopes...)
\t}
\treturn result
}

func Find(id string) (App, bool) {
\tid = strings.TrimSpace(strings.ToLower(id))
\tfor _, candidate := range officialApps {
\t\tif candidate.ID == id {
\t\t\tcandidate.Scopes = append([]string(nil), candidate.Scopes...)
\t\t\treturn candidate, true
\t\t}
\t}
\treturn App{}, false
}

func NormalizeIDs(ids []string) ([]App, bool) {
\tseen := make(map[string]bool, len(ids))
\tapps := make([]App, 0, len(ids))
\tfor _, id := range ids {
\t\titem, ok := Find(id)
\t\tif !ok || seen[item.ID] {
\t\t\treturn nil, false
\t\t}
\t\tseen[item.ID] = true
\t\tapps = append(apps, item)
\t}
\treturn apps, true
}

func Defaults() []App {
\titems, ok := NormalizeIDs([]string{"inbox", "chat", "journal", "files", "agents"})
\tif !ok {
\t\tpanic("default Misty Apps are missing from the catalog")
\t}
\treturn items
}
`;

await writeFile(targetPath, generated);
console.log(`Synced ${catalog.apps.length} official apps to ${targetPath}`);
