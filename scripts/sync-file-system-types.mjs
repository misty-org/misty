/** Copy the native Files IPC types into the SDK without maintaining a second model. */
import ts from "typescript";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
const root = resolve(import.meta.dirname, "..");
const source = resolve(root, "src/native/contracts");
const declarations = new Map();
for (const name of readdirSync(source, {recursive: true}).filter(name => name.endsWith(".ts"))) {
  const file = ts.createSourceFile(name, readFileSync(resolve(source, name), "utf8"), ts.ScriptTarget.Latest, true);
  for (const node of file.statements) {
    if ((ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node)) && node.name)
      declarations.set(node.name.text, { node, file });
  }
}
const names = ["AppEnvironmentSnapshot", "DeviceSnapshot", "ConnectedDevicesSnapshot", "PeerRoot", "ListDirectoryRequest", "DirectoryListing", "FileMetadataSnapshot", "ExplorerPreviewPayload", "PasteItemsRequest", "CreateItemRequest", "RenameItemRequest", "DeleteItemsRequest", "OperationQueueSnapshot", "TransferFilter", "TransferPage"];
const output = new Map();
function include(name) {
  if (output.has(name) || !declarations.has(name)) return;
  const {node, file} = declarations.get(name);
  output.set(name, node.getText(file).replace(/^export\s+/, "export "));
  function visit(node) {
    if (ts.isTypeReferenceNode(node) && ts.isIdentifier(node.typeName)) include(node.typeName.text);
    ts.forEachChild(node, visit);
  }
  visit(node);
}
names.forEach(include);
const text = "// Generated by misty/scripts/sync-file-system-types.mjs from the native IPC contracts.\n" + [...output.values()].join("\n\n") + "\n";
const destination = resolve(root, "../misty-sdk/packages/sdk/src/file-system-types.ts");
if (process.argv.includes("--check")) {
  if (readFileSync(destination, "utf8") !== text) throw new Error("SDK Files types differ from native IPC contracts.");
} else writeFileSync(destination, text);
