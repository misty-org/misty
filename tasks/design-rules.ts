// Writes docs/design/rules.md: every automated UI rule and what to do instead, from
// src/tests/architecture/uiRuleDefinitions.ts. The components and their catalog live in @misty/ui
// (the misty-ui repository); these rules hold Misty's own code to them.
//
//   npm run design:rules
//
// src/tests/architecture/designRules.contract.test.ts fails when the file is out of date.

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
export const rulesPath = join(root, "docs/design/rules.md");

/** The automated UI rules, each with what to do instead, as uiRules.ts reports them. */
export async function buildRules(): Promise<string> {
  const { uiRules, cssRules } = await import("../src/tests/architecture/uiRuleDefinitions.ts");
  const section = (title: string, rules: Record<string, { guidance: string }>) => [
    `## ${title}`,
    "",
    ...Object.entries(rules).map(([id, rule]) => `- \`${id}\`: ${rule.guidance}`),
    "",
  ];
  return `${[
    "<!-- Generated by tasks/design-catalog.ts from src/tests/architecture/uiRuleDefinitions.ts. Don't edit: run `npm run design:rules`. -->",
    "",
    "# Automated UI rules",
    "",
    "`src/tests/architecture/uiRules.ts` counts these in every file at commit. A new break fails the commit; the",
    "baseline only shrinks. Write code that never trips one, rather than code that waits to be caught.",
    "",
    ...section("In components (.tsx, .ts)", uiRules),
    ...section("In stylesheets (.css)", cssRules),
  ]
    .join("\n")
    .trimEnd()}\n`;
}

if (fileURLToPath(import.meta.url) === resolve(process.argv[1] ?? "")) {
  mkdirSync(dirname(rulesPath), { recursive: true });
  writeFileSync(rulesPath, await buildRules());
  console.log(`Wrote ${relative(root, rulesPath)}`);
}
