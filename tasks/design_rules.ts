import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
export const rulesPath = join(root, "docs/design/rules.md");

export async function buildRules(): Promise<string> {
  const { uiRules, cssRules } = await import("../src/tests/architecture/ui_rule_definitions.ts");
  const section = (title: string, rules: Record<string, { guidance: string }>) => [
    `## ${title}`,
    "",
    ...Object.entries(rules).map(([id, rule]) => `- \`${id}\`: ${rule.guidance}`),
    "",
  ];
  return `${[
    "<!-- Generated by tasks/design_catalog.ts from src/tests/architecture/ui_rule_definitions.ts. Don't edit: run `npm run design:rules`. -->",
    "",
    "# Automated UI rules",
    "",
    "`src/tests/architecture/ui_rules.ts` counts these in every file at commit. A new break fails the commit; the",
    "baseline only shrinks. Write code that never trips one, rather than code that waits to be caught.",
    "",
    ...section("In components (.tsx, .ts)", uiRules),
    ...section("In stylesheets (.css)", cssRules),
  ]
    .join("\n")
    .trimEnd()}\n`;
}

if (fileURLToPath(import.meta.url) === resolve(process.argv[1] ?? "")) {
  mkdirSync(dirname(rulesPath), { recursive: true });
  writeFileSync(rulesPath, await buildRules());
  console.log(`Wrote ${relative(root, rulesPath)}`);
}
