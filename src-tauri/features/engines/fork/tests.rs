#[test]
fn anchor_locating_survives_extreme_seq_hints() {
    // `seq_hint` comes from the frontend and is unconstrained.
    // `(parsed[i].seq - hint).abs()` overflows at `i64::MIN` / `i64::MAX`,
    // panicking in dev/test and wrapping to the wrong duplicate turn in release.
    let text = "重复提问";
    let parsed = vec![
        user_message(1, text),
        user_message(3, text),
        user_message(5, text),
    ];
    let anchor = |hint: Option<i64>| ForkAnchor {
        user_text_sha256: text_sha256_hex(text),
        seq_hint: hint,
        tail_occurrence: None,
    };

    // Extremes don't panic and pick by real distance: the nearest.
    assert_eq!(anchor_hit_index(&parsed, &anchor(Some(i64::MIN))), Some(0));
    assert_eq!(anchor_hit_index(&parsed, &anchor(Some(i64::MAX))), Some(2));
    // A tie (1 and 3 are both 1 from 2): the earlier one, so the cut is stable.
    assert_eq!(anchor_hit_index(&parsed, &anchor(Some(2))), Some(0));
    // No hint: the last one (the latest turn).
    assert_eq!(anchor_hit_index(&parsed, &anchor(None)), Some(2));
    // Digests are case-insensitive: the shape check accepts uppercase hex anyway.
    let upper = ForkAnchor {
        user_text_sha256: text_sha256_hex(text).to_ascii_uppercase(),
        seq_hint: Some(3),
        tail_occurrence: None,
    };
    assert_eq!(anchor_hit_index(&parsed, &upper), Some(1));
    // Text that doesn't match: None (the caller reports an error, never falling back to "fork from the end").
    let missing = ForkAnchor {
        user_text_sha256: text_sha256_hex("转录本里没有这句话"),
        seq_hint: Some(i64::MIN),
        tail_occurrence: None,
    };
    assert_eq!(anchor_hit_index(&parsed, &missing), None);
}

#[test]
fn seq_hint_drift_is_what_decides_whether_the_earlier_duplicate_wins() {
    // A characterization test pinning the geometry of `seq_hint` tie-breaking: when the feared "cut a turn
    // early" really happens, and why it can neither be ruled out nor blindly changed.
    //
    // Frontend and backend seqs share a source only when history loads (it carries the backend seq); after that
    // the frontend counts `lastSeq + 1 + i` locally: plan reviews / question cards are frontend-only messages taking a seq
    // the parser never produces. Say two identical texts have backend seqs P1 < P2, and clicking the second sends
    // hint = P2 + drift:
    //   - drift >= 0 (frontend high): distance to P2 is drift, to P1 (P2-P1)+drift; always right;
    //   - drift < 0 (frontend low): `hint = P2 - |drift|`, wrong only when 2·|drift| ≥ P2-P1 (a tie flips too).
    // So: the smaller the gap and the larger |drift|, the easier an early cut. Two adjacent "continue" turns (gap 2)
    // with a drift of -1 already reach the midpoint and flip by "earlier on a tie".
    //
    // The above covers only clicking the later one. The other side can cut wrong too: clicking the earlier one with
    // the frontend high pushes hint past the midpoint, picking the later one, and the branch carries a turn the person didn't click (second group below).
    // The two sides are symmetric, so "high" isn't a safe direction.
    //
    // Whether real machines drift is evidenced by `log_anchor_drift` (one log line per fork); the tie-break isn't changed
    // before that data exists (it would trade one unseen quantity for another). This test is the ruler for reading it.
    let text = "继续";
    let parsed = vec![user_message(10, text), user_message(30, text)];
    let anchor = |hint: i64| ForkAnchor {
        user_text_sha256: text_sha256_hex(text),
        seq_hint: Some(hint),
        tail_occurrence: None,
    };

    // —— clicking the later one (P2=30) ——
    // Frontend high +10 (hint=40): closer to P2 → right.
    assert_eq!(anchor_hit_index(&parsed, &anchor(40)), Some(1));
    // Frontend low -10 (hint=20): a tie with P1 → the earlier → cut a turn early (missing the clicked turn).
    assert_eq!(anchor_hit_index(&parsed, &anchor(20)), Some(0));
    // The same negative drift with a large enough gap (P1=1, P2=30, hint=20): still right.
    let wide = vec![user_message(1, text), user_message(30, text)];
    assert_eq!(anchor_hit_index(&wide, &anchor(20)), Some(1));

    // —— clicking the earlier one (P1=10): frontend high pushes it just past the midpoint ——
    // Adjacent turns + the frontend 2 high: hint=12 is 2 from P1 and 0 from P2=12 → picks the later one,
    // and the branch carries an extra turn; the log then prints drift=0, the easiest to misread as "no drift, safe".
    let adjacent = vec![user_message(10, text), user_message(12, text)];
    assert_eq!(anchor_hit_index(&adjacent, &anchor(12)), Some(1));
}

#[test]
fn resolve_fork_plan_carries_the_source_workspace_and_honest_tip_flag() {
    // All in the shape of "the plan the command returns to the frontend".
    // The two turns with the repeated question (0 and 2) check anchor location through the whole command path.
    let source_id = "11111111-1111-4111-8111-111111111111";
    let workspace = "C:/repo/source-ws";
    let dup = "重复提问";
    let mid = "中间那轮";
    let body = [
        claude_user_line(source_id, dup, false, "2026-10-22T11:00:00.000Z"),
        claude_assistant_line(source_id, "A1", "2026-10-22T11:00:01.000Z"),
        claude_user_line(source_id, mid, false, "2026-10-22T11:00:02.000Z"),
        claude_assistant_line(source_id, "A2", "2026-10-22T11:00:03.000Z"),
        claude_user_line(source_id, dup, false, "2026-10-22T11:00:04.000Z"),
        claude_assistant_line(source_id, "A3", "2026-10-22T11:00:05.000Z"),
    ]
    .join("\n")
        + "\n";
    let (dir, db, _source_path) = fork_source_fixture("claude", source_id, workspace, &body);
    let anchor = |text: &str, hint: Option<i64>| ForkAnchor {
        user_text_sha256: text_sha256_hex(text),
        seq_hint: hint,
        tail_occurrence: None,
    };

    // Tip fork: the whole file moves, and the workspace must come from the source session row, not the caller's
    // current one (the frontend opens the tab in it, or the branch would spawn in another cwd).
    let tip = resolve_fork_plan(&db, "claude", source_id, None).unwrap();
    assert!(tip.at_tip);
    // Keeping the whole file sends no count: `usize::MAX` through JSON reads in JS as
    // 18446744073709552000 (precision lost); one field meaning both "how many" and "all"
    // is a trap. `at_tip` says it, and the sentinel never leaves.
    assert_eq!(
        tip.keep_records, None,
        "keeping everything must not send usize::MAX over the wire (JS loses precision)"
    );
    assert_eq!(tip.workspace_path, workspace, "the plan must carry the source workspace");
    assert_eq!(tip.source_title, "重复提问");
    assert!(is_uuid(&tip.target_session_id));

    // One hit: the cut is the line of the turn after it (user line table [0,2,4,MAX]).
    let middle =
        resolve_fork_plan(&db, "claude", source_id, Some(&anchor(mid, Some(2)))).unwrap();
    assert_eq!(middle.keep_records, Some(4));
    assert!(!middle.at_tip);

    // An uppercase digest must equal the lowercase one: the shape check accepts uppercase hex, while `text_sha256_hex`
    // produces only lowercase, and without folding it would end in "couldn't find this turn's fork point".
    let mut upper = anchor(mid, Some(2));
    upper.user_text_sha256 = upper.user_text_sha256.to_ascii_uppercase();
    let upper_plan = resolve_fork_plan(&db, "claude", source_id, Some(&upper)).unwrap();
    assert_eq!(upper_plan.keep_records, Some(4), "an uppercase digest must hit the same turn");

    // Extreme seq_hint: no panic, and picks the right duplicate turn by real distance.
    let first =
        resolve_fork_plan(&db, "claude", source_id, Some(&anchor(dup, Some(i64::MIN))))
            .unwrap();
    assert_eq!(first.keep_records, Some(2), "i64::MIN picks the earliest duplicate turn");
    assert!(!first.at_tip);
    let last = resolve_fork_plan(&db, "claude", source_id, Some(&anchor(dup, Some(i64::MAX))))
        .unwrap();
    assert_eq!(
        last.keep_records,
        None,
        "i64::MAX picks the latest duplicate turn (= the last turn → keep everything, the sentinel stays off the wire)"
    );
    // When the anchor is exactly the last turn the cut is also usize::MAX (the whole file moved): checking only
    // `at.is_none()` would report false for the same "keep everything".
    assert!(last.at_tip, "being at the end depends on the actual cut, not on whether there is an anchor");

    // Text that doesn't match → an explicit error (never falling back to "fork from the end").
    let missing = resolve_fork_plan(
        &db,
        "claude",
        source_id,
        Some(&anchor("转录本里没有这句话", Some(i64::MIN))),
    );
    assert!(missing.unwrap_err().contains("Couldn't find this turn's fork point"));

    let _ = std::fs::remove_dir_all(&dir);
}

