#[test]
fn deep_fork_nesting_elides_to_five_segments_behind_an_ellipsis() {
    // Deep nesting: without caps the name would grow without bound fork after fork. The caps are at most 5
    // suffix segments + at most 80 characters in all, with earlier segments elided as `…`.
    let (dir, db) = naming_db("ccgui-fork-name-depth");
    let mut parent = "A".to_string();
    let mut produced = Vec::new();
    for level in 0..7 {
        let title = next_fork_title(&db, "claude", &parent).unwrap();
        // Each level is really registered in the table: numbering only reads the table, and without inserting the
        // next level isn't realistic (how `title` and `custom_title` fold affects the sibling set).
        insert_named_session(
            &db,
            "claude",
            &format!("00000000-0000-4000-8000-{level:012}"),
            Some(&title),
            "derived transcript title",
        );
        produced.push(title.clone());
        parent = title;
    }

    // Levels 1..5 are as before: each fork adds a segment, nothing elided.
    assert_eq!(produced[0], "A (fork #1)");
    assert_eq!(
        produced[4],
        "A (fork #1) (fork #1) (fork #1) (fork #1) (fork #1)"
    );
    // Level 6: with the new segment that's 6 → only the newest 5 stay, and a `…` goes after the root.
    assert_eq!(
        produced[5],
        "A … (fork #1) (fork #1) (fork #1) (fork #1) (fork #1)"
    );
    assert!(produced[5].contains(FORK_ELISION_MARK), "the elision must be visible");
    // Level 7: the candidate equals level 6's name (the parent already has `…`, and `#1` is the start computed
    // from the full parent name), so the duplicate check bumps it to `#2`. This is the "cap produces a duplicate" path.
    assert_eq!(
        produced[6],
        "A … (fork #1) (fork #1) (fork #1) (fork #1) (fork #2)"
    );
    // No level exceeds the caps: ≤ 5 segments, ≤ 80 characters.
    for title in &produced {
        assert!(
            title.matches(FORK_MARK).count() <= MAX_FORK_SUFFIX_SEGMENTS,
            "the suffix chain exceeds the segment cap: {title}"
        );
        assert!(
            title.chars().count() <= MAX_FORK_TITLE_CHARS,
            "the title exceeds the character budget: {title}"
        );
    }

    let _ = std::fs::remove_dir_all(&dir);
}

#[test]
fn a_long_fork_title_truncates_the_root_and_keeps_the_suffix_chain() {
    // Character budget: over 80, only the root can be cut; under the segment cap the chain is at most 5
    // segments and always fits; `…` and the chain are a fixed tail and can't be cut.
    let (dir, db) = naming_db("ccgui-fork-name-budget");
    // 100 CJK characters = 300 bytes: cutting bytes would panic or split a character; cutting characters is right.
    let root = "题".repeat(100);
    let parent = format!("{root} (fork #2) (fork #3) (fork #4) (fork #5) (fork #6)");
    let title = next_fork_title(&db, "claude", &parent).unwrap();

    // Tail = ` …` (2) + 5 segments (`(fork #k)` 9 characters + a separating space = 10 each) = 52,
    // so the root gets 80 - 52 = 28 characters. The tail already has `…` (the segment cap dropped some),
    // so a cut root gets no second one (two ellipses in one title can't say which part was left out), and that 1
    // character isn't reserved either, so the root still takes all 28 characters.
    assert_eq!(
        title.chars().count(),
        MAX_FORK_TITLE_CHARS,
        "over budget, the budget must be used exactly: {title}"
    );
    assert!(title.starts_with(&"题".repeat(28)), "the root is cut to the budget by character: {title}");
    assert!(title.contains(FORK_ELISION_MARK), "the elision mark must not be cut: {title}");
    assert_eq!(
        title.matches(FORK_ELISION_MARK).count(),
        1,
        "with `…` already in the tail the root gets no second one: {title}"
    );
    assert!(
        title.ends_with("(fork #3) (fork #4) (fork #5) (fork #6) (fork #1)"),
        "the whole suffix chain must stay as is (the oldest #2 was dropped by the segment cap): {title}"
    );
    assert!(!title.contains("(fork #2)"), "the oldest segment was elided: {title}");

    // The same without a chain: the whole budget goes to the root (80 - the 10 characters of ` (fork #1)` = 70),
    // but when the root is cut its last character must be left for `…`: `history::truncate_chars` is silent,
    // and without the mark `题×100` would be cut to a complete-looking `题×70`; nobody could tell it was cut.
    let plain = next_fork_title(&db, "claude", &root).unwrap();
    assert_eq!(plain.chars().count(), MAX_FORK_TITLE_CHARS);
    assert_eq!(
        plain.strip_suffix(" (fork #1)"),
        Some(format!("{}…", "题".repeat(69)).as_str()),
        "with one segment the root gets 70 characters, the last being the elision mark: {plain}"
    );
    assert_eq!(
        plain.trim_end_matches(" (fork #1)").chars().last(),
        Some(FORK_ELISION_MARK),
        "a cut root must end with `…`: {plain}"
    );

    let _ = std::fs::remove_dir_all(&dir);
}

#[test]
fn a_root_cut_by_the_budget_ends_with_a_visible_ellipsis() {
    // Cutting the root must leave a trace too (the same convention as `git.rs`'s explicit marker when it
    // cuts a diff): `history::truncate_chars` only does `chars().take(max)` with no signal,
    // so adding `…` is this code's job, and that 1 character must really come out of the budget: adding without
    // taking goes over budget, taking without adding leaves the string one character short (79 of 80).
    let (dir, db) = naming_db("ccgui-fork-name-root-marker");

    // The root exactly fills the budget (80 - the 10 characters of ` (fork #1)` = 70): not cut, so no
    // `…` should appear from nowhere.
    let title = next_fork_title(&db, "claude", &"题".repeat(70)).unwrap();
    assert_eq!(title, format!("{} (fork #1)", "题".repeat(70)));
    assert!(
        !title.contains(FORK_ELISION_MARK),
        "a root that wasn't cut must not get an elision mark: {title}"
    );

    // One character over still counts as cut: a 69-character root + `…` = the budget's 70 characters, the whole
    // string exactly 80; the reserved character must really be used by `…`.
    let title = next_fork_title(&db, "claude", &"题".repeat(71)).unwrap();
    assert_eq!(
        title.chars().count(),
        MAX_FORK_TITLE_CHARS,
        "a cut must also use the budget exactly: {title}"
    );
    assert_eq!(
        title.strip_suffix(" (fork #1)"),
        Some(format!("{}…", "题".repeat(69)).as_str()),
        "a cut root must end with `…`: {title}"
    );

    // When the tail already has `…` (the parent name carries the mark the segment cap left): a cut root
    // gets no second one, and that character isn't reserved either; reserving unconditionally would give 79
    // characters (not filling the 80 budget).
    let parent = format!("{} … (fork #1) (fork #3)", "题".repeat(100));
    let title = next_fork_title(&db, "claude", &parent).unwrap();
    assert_eq!(
        title.chars().count(),
        MAX_FORK_TITLE_CHARS,
        "with a mark already in the tail the budget must still be used exactly (reserving without inserting is 1 short): {title}"
    );
    assert_eq!(
        title.matches(FORK_ELISION_MARK).count(),
        1,
        "a title can't have two ellipses: {title}"
    );
    assert_eq!(
        title,
        format!("{} … (fork #1) (fork #3) (fork #1)", "题".repeat(48)),
        "the 32-character tail (` …` + 3 segments of 10) leaves the root 48 characters"
    );

    let _ = std::fs::remove_dir_all(&dir);
}

/// Forking a fork that the budget cut never gives a title equal to the parent's.
///
/// Worth its own test: `strip_elision_marker` can only report "there was a `…`", not whether
/// segments were elided or the root was cut by the budget, so `add_marker` could be pushed to false, the
/// root get no mark, and parent and child names collapse into one string that even `taken_titles` can't
/// save (two equal strings are inseparable in a `HashSet`).
///
/// By arithmetic it can't happen: the child always has one more suffix segment, so its root is about 11
/// characters shorter and the strings can't be equal. Both root lengths are pinned here (exactly filling
/// the budget, not cut; and 1 over, cut with `…`), through `next_fork_title`'s real duplicate check too.
#[test]
fn forking_a_budget_truncated_branch_never_reuses_the_parent_title() {
    // A one-segment tail ` (fork #1)` takes 10 characters ⇒ a root budget of 70.
    for root_len in [70usize, 71] {
        let root = "题".repeat(root_len);
        let first = capped_fork_title(&root, 1);
        let second = capped_fork_title(&first, 1);

        assert!(
            first.chars().count() <= MAX_FORK_TITLE_CHARS,
            "the first level shouldn't exceed the budget ({root_len}-character root): {first:?}"
        );
        assert!(
            second.chars().count() <= MAX_FORK_TITLE_CHARS,
            "the second level shouldn't exceed the budget either ({root_len}-character root): {second:?}"
        );
        assert_ne!(
            first, root,
            "a branch title must add the new segment, not equal the parent ({root_len}-character root)"
        );
        assert_ne!(
            second, first,
            "forking a cut branch must never give the parent's own title ({root_len}-character root)"
        );
    }

    // The real path: the first fork's result is registered in the table at once (writing `custom_title`), so the
    // second fork sees it. The two must differ.
    let (dir, db) = naming_db("ccgui-fork-truncated-branch-chain");
    for (n, root_len) in [70usize, 71].into_iter().enumerate() {
        let root = "题".repeat(root_len);
        let a = next_fork_title(&db, "claude", &root).unwrap();
        // A different id each round: (engine, session_id) is unique in `sessions`.
        insert_named_session(
            &db,
            "claude",
            &format!("00000000-0000-4000-8000-{n:012}"),
            Some(&a),
            "derived transcript title",
        );
        let b = next_fork_title(&db, "claude", &a).unwrap();
        assert_ne!(b, a, "forking along a cut branch, parent and child can't share a name ({root_len}-character root)");
    }
    let _ = std::fs::remove_dir_all(&dir);
}

#[test]
fn collapsed_fork_titles_still_get_a_free_number() {
    // The caps can squeeze different parent names into one string (roots cut to the same prefix, or chains
    // elided to the same 5 segments). Then `taken_titles`' duplicate check must bump the number, or two sessions
    // share a name the sidebar can't tell apart.
    let (dir, db) = naming_db("ccgui-fork-name-collapse");

    // (1) A collision after the root is cut: two parent names differing only at character 101 are identical
    // once cut to the budget (a 69-character root + `…`). The cut leaves `…`, so "the taken candidate" also has
    // the marked shape (the unmarked `题×70 + " (fork #1)"` is no longer a name this module produces).
    let root_a = format!("{}甲", "题".repeat(100));
    let root_b = format!("{}乙", "题".repeat(100));
    let collapsed = format!("{}… (fork #1)", "题".repeat(69));
    insert_named_session(
        &db,
        "claude",
        "00000000-0000-4000-8000-000000000001",
        None,
        &collapsed,
    );
    let a = next_fork_title(&db, "claude", &root_a).unwrap();
    assert_eq!(
        a,
        format!("{}… (fork #2)", "题".repeat(69)),
        "candidate #1 has the taken name's shape; the duplicate check must bump the number"
    );
    assert_ne!(a, collapsed, "a taken candidate must never go out as is");

    // Two different parent names squeezed into one root must still differ: in the real flow the fork result is
    // registered at once (`register_fork_landing_with_path` writes `custom_title`), so the second
    // fork always sees the first branch holding that candidate, and the number moves on.
    insert_named_session(
        &db,
        "claude",
        "00000000-0000-4000-8000-000000000003",
        Some(&a),
        "derived transcript title",
    );
    let b = next_fork_title(&db, "claude", &root_b).unwrap();
    assert_eq!(b, format!("{}… (fork #3)", "题".repeat(69)));
    assert_ne!(b, a, "two parent names squeezed into one string must never give two branches the same name");

    // (2) A collision after the chain is elided: both parent names differ in new and old segments, but after the
    // new segment the newest 5 match (segment 6 and segment 1 both dropped), giving one candidate string again.
    let parent_long = "A (fork #1) (fork #2) (fork #3) (fork #4) (fork #5) (fork #6)";
    // An elided branch has exactly the "root with `…` + 5 segments" shape (what the cap itself produces).
    let parent_elided = "A … (fork #9) (fork #3) (fork #4) (fork #5) (fork #6)";
    insert_named_session(
        &db,
        "claude",
        "00000000-0000-4000-8000-000000000002",
        Some("A … (fork #3) (fork #4) (fork #5) (fork #6) (fork #1)"),
        "derived transcript title",
    );
    let c = next_fork_title(&db, "claude", parent_long).unwrap();
    let d = next_fork_title(&db, "claude", parent_elided).unwrap();
    assert_eq!(c, "A … (fork #3) (fork #4) (fork #5) (fork #6) (fork #2)");
    assert_eq!(d, c, "an elided duplicate candidate must also give way on the number");

    let _ = std::fs::remove_dir_all(&dir);
}

