#[test]
fn fork_numbers_do_not_count_grandchildren_as_siblings() {
    // This pins the step easiest to get wrong: siblings must match the whole string.
    // With a prefix check (`name.starts_with("A (fork #")`), the grandchild below,
    // `A (fork #1) (fork #1)`, would count as `A`'s sibling, giving `A`'s new fork
    // `A (fork #3)`, while the right answer is #2.
    let (dir, db) = naming_db("ccgui-fork-name-trap");
    let custom = |db: &crate::engines::support::db::Db, id: &str, name: &str| {
        insert_named_session(db, "claude", id, Some(name), "derived transcript title");
    };
    custom(&db, "00000000-0000-4000-8000-000000000001", "A");
    custom(&db, "00000000-0000-4000-8000-000000000002", "A (fork #1)");
    custom(
        &db,
        "00000000-0000-4000-8000-000000000003",
        "A (fork #1) (fork #1)",
    );

    assert_eq!(
        next_fork_title(&db, "claude", "A").unwrap(),
        "A (fork #2)",
        "a grandchild isn't A's sibling: a prefix check would give #3 here"
    );
    // Pinned the other way too: when forking that fork (its current name is `A (fork #1)`) the grandchild
    // is its sibling, so the next is `(fork #2)`.
    assert_eq!(
        next_fork_title(&db, "claude", "A (fork #1)").unwrap(),
        "A (fork #1) (fork #2)"
    );

    let _ = std::fs::remove_dir_all(&dir);
}

#[test]
fn forking_a_branch_appends_and_keeps_the_lineage() {
    // The naming rule's core behavior: append to the source's current name, stripping no suffix, so lineage
    // shows in the name: `A (fork #1) (fork #1)`. Stripping the trailing `(fork #N)` would give
    // `A (fork #2)`, with the lineage hidden.
    let (dir, db) = naming_db("ccgui-fork-name-lineage");
    insert_named_session(&db, "claude", "00000000-0000-4000-8000-000000000001", None, "A");
    let name = |db: &crate::engines::support::db::Db, id: &str| -> String {
        db.0.lock()
            .query_row(
                "SELECT COALESCE(custom_title, title) FROM cli_sessions
                  WHERE engine='claude' AND session_id=?1",
                [id],
                |r| r.get(0),
            )
            .unwrap()
    };

    // First fork: no sibling under source name `A` → #1.
    assert_eq!(next_fork_title(&db, "claude", "A").unwrap(), "A (fork #1)");
    insert_named_session(
        &db,
        "claude",
        "00000000-0000-4000-8000-000000000002",
        Some("A (fork #1)"),
        "derived transcript title",
    );
    // Forking that fork: its current name is `A (fork #1)`; appending gives `(fork #1)`.
    assert_eq!(
        next_fork_title(&db, "claude", &name(&db, "00000000-0000-4000-8000-000000000002"))
            .unwrap(),
        "A (fork #1) (fork #1)",
        "forking a fork must show the lineage"
    );
    insert_named_session(
        &db,
        "claude",
        "00000000-0000-4000-8000-000000000003",
        Some("A (fork #1) (fork #1)"),
        "derived transcript title",
    );
    // Forking the source again: the only sibling is still `A (fork #1)` (the grandchild isn't its sibling, see the
    // previous test), so #2, not #3.
    assert_eq!(next_fork_title(&db, "claude", "A").unwrap(), "A (fork #2)");
    // The source's own name was changed by no fork (forking an unrenamed session repeatedly gives 1, 2, …).
    assert_eq!(name(&db, "00000000-0000-4000-8000-000000000001"), "A");
    // Conversely the source name can come straight from the table's current name, as `resolve_fork_plan` takes it.
    assert_eq!(name(&db, "00000000-0000-4000-8000-000000000002"), "A (fork #1)");

    let _ = std::fs::remove_dir_all(&dir);
}

