#[test]
fn copied_frames_are_bounded_by_the_same_caps_as_live_recording() {
    // Copying `accepted_internal_frames` is one `INSERT ... SELECT`, and its cap must match
    // the IPC path (5 000 per session / 100 000 in all):
    // `record_accepted_internal_frame_hash` has no cap at all (its `Ok(false)`
    // only means "this identity already exists"), and calling it per frame would turn the cap into guesswork.
    let source_id = "11111111-1111-4111-8111-111111111111";
    let target = "22222222-2222-4222-8222-222222222222";
    let body = claude_user_line(source_id, "你好", false, "2026-10-22T11:00:00.000Z") + "\n";
    let (dir, db, _source_path) = fork_source_fixture("claude", source_id, "C:/repo", &body);
    db.record_accepted_internal_frame_hash("claude", source_id, &"a".repeat(64), "C:/repo")
        .unwrap();
    db.record_accepted_internal_frame_hash("claude", source_id, &"b".repeat(64), "C:/repo")
        .unwrap();

    // First fill this branch row's per-session quota (a recursive CTE writes 5 000 in one statement).
    {
        let conn = db.0.lock();
        conn.execute(
            "WITH RECURSIVE c(x) AS (SELECT 0 UNION ALL SELECT x+1 FROM c WHERE x < ?2 - 1)
             INSERT INTO cli_accepted_internal_frames(engine, session_id, frame_hash, workspace_path)
             SELECT 'claude', ?1, printf('pre%06d', x), '/ws' FROM c",
            rusqlite::params![target, MAX_RECORDED_FRAMES_PER_SESSION],
        )
        .unwrap();
    }
    assert_eq!(
        frame_row_count(&db, "claude", target),
        MAX_RECORDED_FRAMES_PER_SESSION
    );
    {
        let conn = db.0.lock();
        let error = copy_accepted_frames(&conn, "claude", source_id, target, "/ws", 2)
            .expect_err("a full quota must be an error, not silently copying fewer");
        assert!(error.contains("limit"), "{error}");
    }

    // Copying the whole set onto an empty target: one to one, and the FTS stamps cleared, since a stamp only
    // tracks file stat + INDEX_VERSION, and without clearing it copied internal frame text stays searchable forever.
    let target2 = "33333333-3333-4333-8333-333333333333";
    {
        let conn = db.0.lock();
        // `fts_state` has a foreign key to `sessions` (`PRAGMA foreign_keys=ON`),
        // so give the branch a session row first for the stamp to hang on.
        conn.execute(
            "INSERT INTO cli_sessions(engine, session_id, workspace_path, file_path, file_size, file_mtime_ms)
             VALUES('claude', ?1, '/ws', '/ws/x.jsonl', 0, 0)",
            rusqlite::params![target2],
        )
        .unwrap();
        conn.execute(
            "INSERT INTO cli_fts_state(engine, session_id, file_size, file_mtime_ms, version, indexed_at)
             VALUES('claude', ?1, 1, 1, '1', 1)",
            rusqlite::params![target2],
        )
        .unwrap();
        copy_accepted_frames(&conn, "claude", source_id, target2, "/ws", 2).unwrap();
        let copied: Vec<String> = {
            let mut stmt = conn
                .prepare(
                    "SELECT frame_hash FROM cli_accepted_internal_frames
                      WHERE engine='claude' AND session_id=?1 ORDER BY frame_hash",
                )
                .unwrap();
            let rows = stmt
                .query_map(rusqlite::params![target2], |r| r.get::<_, String>(0))
                .unwrap();
            rows.map(|r| r.unwrap()).collect()
        };
        assert_eq!(copied, vec!["a".repeat(64), "b".repeat(64)]);
        let stamped: i64 = conn
            .query_row(
                "SELECT COUNT(*) FROM cli_fts_state WHERE engine='claude' AND session_id=?1",
                rusqlite::params![target2],
                |r| r.get(0),
            )
            .unwrap();
        assert_eq!(stamped, 0, "after copying, the index must re-derive from the new identity set");
    }

    let _ = std::fs::remove_dir_all(&dir);
}

#[test]
fn tail_occurrence_pins_the_exact_duplicate_regardless_of_seq_drift() {
    // A bug reproduced on a real machine: three "continue" messages in a row, forking at the middle one gave a
    // branch with all three turns (judged as the last). The cause: `seq_hint` and the backend seq have different sources: the frontend
    // counts plan/question cards as local messages with a seq, and a drift of one or two puts "the middle one" closer to the next.
    //
    // `tail_occurrence` only counts how many same-text messages follow, independent of numbering, so drift can't move it.
    let text = "继续";
    let parsed = vec![
        user_message(10, text),
        user_message(14, text),
        user_message(18, text),
    ];
    let anchor = |tail: Option<u32>, hint: Option<i64>| ForkAnchor {
        user_text_sha256: text_sha256_hex(text),
        seq_hint: hint,
        tail_occurrence: tail,
    };

    // Counted from the end: 0=last, 1=middle, 2=first. Even when drift has pushed hint near the next one,
    // tail still locates the one the person really clicked.
    assert_eq!(anchor_hit_index(&parsed, &anchor(Some(0), Some(18))), Some(2));
    assert_eq!(anchor_hit_index(&parsed, &anchor(Some(1), Some(20))), Some(1));
    assert_eq!(anchor_hit_index(&parsed, &anchor(Some(2), Some(12))), Some(0));

    // An out-of-range tail (possible when the frontend window and transcript disagree) falls back to the nearest seq, without panicking or going out of bounds.
    assert_eq!(anchor_hit_index(&parsed, &anchor(Some(9), Some(18))), Some(2));
    // An older frontend that sends no tail behaves as before (nearest).
    assert_eq!(anchor_hit_index(&parsed, &anchor(None, Some(14))), Some(1));
}

/// Writes a Codex rollout at `<root>/<rel>` (creating directories as needed) and returns its path.
fn write_codex_rollout(root: &Path, rel: &str, lines: &[serde_json::Value]) -> PathBuf {
    let path = root.join(rel);
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    let body: String = lines.iter().map(|line| format!("{line}\n")).collect();
    std::fs::write(&path, body).unwrap();
    path
}

fn read_json_lines(path: &Path) -> Vec<serde_json::Value> {
    std::fs::read_to_string(path)
        .unwrap()
        .lines()
        .map(|line| serde_json::from_str(line).unwrap())
        .collect()
}

/// The branch's first `session_meta` has the shape of Codex's own fork (measured with 0.164 `codex exec fork`):
/// new `id` / `session_id`, `forked_from_id` pointing at the source; `cwd` untouched. Without
/// `forked_from_id`, usage statistics would count the copied old usage again as a "new lineage". A replayed
/// parent `session_meta` (left by older native forks) describes the parent and stays as is.
#[test]
fn codex_branch_identity_matches_the_native_fork_shape() {
    let root = std::env::temp_dir().join(format!("ccgui-codex-id-{}", uuid::Uuid::new_v4()));
    let src_id = "01a191b1-7741-71b1-b55b-74b820b5210f";
    let meta = serde_json::json!({"type": "session_meta", "payload": {
        "id": src_id, "session_id": src_id, "cwd": "/w", "history_mode": "paginated"}});
    let replayed = serde_json::json!({"type": "session_meta", "payload": {"id": "parent", "cwd": "/w"}});
    let user = serde_json::json!({"type": "response_item", "payload": {"type": "message", "role": "user",
        "content": [{"type": "input_text", "text": "Q1"}]}});
    let source = write_codex_rollout(
        &root,
        &format!("home/sessions/2025/01/02/rollout-2025-01-02T03-04-05-{src_id}.jsonl"),
        &[meta, replayed.clone(), user.clone()],
    );

    let target = "8a1b2c3d-4e5f-4a6b-8c7d-9e0f1a2b3c4d";
    let written = codex_copy_prefix(&source, target, usize::MAX).unwrap();
    let lines = read_json_lines(&written);
    let head = &lines[0]["payload"];
    assert_eq!(head["id"], target);
    assert_eq!(head["session_id"], target, "with session_id left as the source's, Codex treats the branch as the source session");
    assert_eq!(head["forked_from_id"], src_id, "without lineage, usage statistics double count");
    assert_eq!(head["cwd"], "/w");
    assert_eq!(head["history_mode"], "paginated", "other fields stay as they are");
    assert_eq!(lines[1], replayed, "only the first session_meta changes");
    assert_eq!(lines[2], user);
    let _ = std::fs::remove_dir_all(&root);
}

/// When the source is itself a native fork, its `forked_from_id` and `history_base` point at the ancestor together
/// (0.164's native fork copies no history and refers to it through `history_base`). The branch must keep that lineage:
/// overwriting `forked_from_id` would contradict `history_base`. An older format without `session_id`
