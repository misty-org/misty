#[test]
fn sha256_matches_the_frontend_implementation() {
    // Matching `src/lib/sha256.ts` byte for byte is a hard requirement: the frontend hashes the user message
    // it holds and the backend finds it in the transcript by that digest. The four vectors come from the
    // frontend implementation's output; CJK and emoji cover multi-byte UTF-8 and surrogate pairs.
    assert_eq!(
        text_sha256_hex(""),
        "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
    );
    assert_eq!(
        text_sha256_hex("abc"),
        "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
    );
    assert_eq!(
        text_sha256_hex("你好，你是谁"),
        "c8602108e6785150c66dea21774d99aaa0cfbce1f0b3105356a0e96e2bb4651e"
    );
    assert_eq!(
        text_sha256_hex("🀄️ fork"),
        "cc1500f9cff7d754ce685d941a75d321e9582eb7ef8cb00d5e09d3d15a3d2253"
    );
}

