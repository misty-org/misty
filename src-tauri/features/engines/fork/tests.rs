/// One standard user record of a Claude transcript.
fn claude_user_line(session_id: &str, text: &str, is_meta: bool, ts: &str) -> String {
    serde_json::json!({
        "type": "user",
        "uuid": uuid::Uuid::new_v4().to_string(),
        "parentUuid": serde_json::Value::Null,
        "sessionId": session_id,
        "timestamp": ts,
        "isMeta": is_meta,
        "message": { "role": "user", "content": [{ "type": "text", "text": text }] }
    })
    .to_string()
}

/// One standard assistant record of a Claude transcript.
fn claude_assistant_line(session_id: &str, text: &str, ts: &str) -> String {
    serde_json::json!({
        "type": "assistant",
        "uuid": uuid::Uuid::new_v4().to_string(),
        "parentUuid": serde_json::Value::Null,
        "sessionId": session_id,
        "timestamp": ts,
        "message": { "role": "assistant", "content": [{ "type": "text", "text": text }] }
    })
    .to_string()
}

/// Copies a prefix at the cut (the same rule as `materialize_trimmed_fork`: the first `keep` lines).
fn copy_first_lines(bytes: &str, keep: usize) -> String {
    bytes
        .lines()
        .take(keep)
        .map(|line| format!("{line}\n"))
        .collect()
}

/// Writes the first `keep` lines as a real branch file and reads it back with the ordinary parser: which
/// messages the branch really has only counts when seen this way (the cut is a line count, not a message count).
fn parse_first_lines(bytes: &str, keep: usize) -> Vec<crate::engines::history::Message> {
    let dir = std::env::temp_dir().join(format!("ccgui-fork-copy-{}", uuid::Uuid::new_v4()));
    std::fs::create_dir_all(&dir).unwrap();
    let path = dir.join("branch.jsonl");
    let body = copy_first_lines(bytes, keep);
    std::fs::write(&path, body).unwrap();
    let parsed =
        crate::engines::history::parse_session_file("claude", &path, &std::collections::HashSet::new())
            .unwrap();
    let _ = std::fs::remove_dir_all(&dir);
    parsed.messages
}

#[test]
fn claude_fork_cut_keeps_exactly_the_anchored_turn() {
    // The anchor turn's end must be computed by the extractor itself. A second "nth user record"
    // rule inevitably disagrees with what the extractor shows: it would count `<local-command-stdout>`
    // (which the extractor drops) and skip skill command envelopes and image-only turns (which it keeps).
    // The errors can cancel out, and the net effect shifts the whole cut: anchored on turn 0 it cuts into
    // CLI chrome (the branch has no message at all), anchored on "what can you do" it can't count 5 and
    // reports a location failure. One of each shape is here, so any drift turns red at once.
    let session_id = "11111111-1111-4111-8111-111111111111";
    let caveat = "<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>";
    let model = "<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args></command-args>";
    let stdout = "<local-command-stdout>Set model to `Opus 5.5` and saved as your default for new sessions</local-command-stdout>";
    let skill = "<command-message>aimax:code-review</command-message>\n<command-name>/aimax:code-review</command-name>\n<command-args>审查1772</command-args>";
    let lines = vec![
        // 0 caveat: opens a local command window, which the extractor drops entirely.
        claude_user_line(session_id, caveat, true, "2026-10-22T11:00:00.000Z"),
        // 1 the /model envelope inside the window: dropped (the window swallows the envelope too).
        claude_user_line(session_id, model, false, "2026-10-22T11:00:01.000Z"),
        // 2 stdout: dropped; counting it as a user record shifts the cut (difference one).
        claude_user_line(session_id, stdout, false, "2026-10-22T11:00:02.000Z"),
        // 3 the first real question: closes the command window. Anchor turn 0.
        claude_user_line(session_id, "先看一眼仓库结构", false, "2026-10-22T11:00:03.000Z"),
        claude_assistant_line(session_id, "仓库不大", "2026-10-22T11:00:04.000Z"),
        // 5 skill envelope (window closed, no caveat): kept by the extractor as `command args`,
        // a visible user row; skipping it by envelope shifts the cut (difference two).
        claude_user_line(session_id, skill, false, "2026-10-22T11:00:05.000Z"),
        claude_assistant_line(session_id, "看过了", "2026-10-22T11:00:06.000Z"),
        // 7 image-only turn: empty text but images present, kept by the extractor as a user row with empty
        // text, also a valid cut position; skipping it by image block shifts the cut (difference three).
        claude_image_only_line(session_id, "2026-10-22T11:00:07.000Z"),
        // 8
        claude_user_line(session_id, "你能干啥", false, "2026-10-22T11:00:08.000Z"),
        claude_assistant_line(session_id, "啥都能干", "2026-10-22T11:00:09.000Z"),
        // 10 the last turn
        claude_user_line(session_id, "那再来一个", false, "2026-10-22T11:00:10.000Z"),
        claude_assistant_line(session_id, "好", "2026-10-22T11:00:11.000Z"),
    ];
    let bytes = lines.join("\n") + "\n";
    let dir = std::env::temp_dir().join(format!("ccgui-fork-{}", uuid::Uuid::new_v4()));
    std::fs::create_dir_all(&dir).unwrap();
    let path = dir.join(format!("{session_id}.jsonl"));
    std::fs::write(&path, &bytes).unwrap();

    let frames = std::collections::HashSet::new();
    let parsed = crate::engines::history::parse_session_file("claude", &path, &frames).unwrap();
    assert_eq!(
        parsed
            .messages
            .iter()
            .map(|m| m.text.as_str())
            .collect::<Vec<_>>(),
        [
            "先看一眼仓库结构",
            "仓库不大",
            // skill envelope: the extractor shows it as `command args`
            "/aimax:code-review 审查1772",
            "看过了",
            "", // image-only turn: the extractor keeps it as a user row with empty text
            "你能干啥",
            "啥都能干",
            "那再来一个",
            "好",
        ],
        "fixture premise: what the extractor shows (if this changes, the expected cuts change with it)"
    );

    // Turn 0 (the first real question): its end = the line of turn 1 (the skill envelope).
    // Counting line 2's stdout too would put the cut on line 3: the branch would hold only CLI
    // chrome, no message at all, and no error.
    let anchor0 = ForkAnchor {
        user_text_sha256: text_sha256_hex("先看一眼仓库结构"),
        seq_hint: Some(1),
        tail_occurrence: None,
    };
    let cut0 = fork_keep_count(&path, &anchor0, &parsed.messages, &frames).unwrap();
    assert_eq!(cut0, 5, "turn 0 ends at turn 1's line (the skill envelope)");
    assert_eq!(
        parse_first_lines(&bytes, cut0)
            .iter()
            .map(|m| m.text.as_str())
            .collect::<Vec<_>>(),
        ["先看一眼仓库结构", "仓库不大"],
        "a turn 0 branch can't drag in any later turn"
    );

    // Turn 1 = the skill envelope turn: a visible user row the extractor accepts. Skipping it
    // moves the cut later and drags the image turn into the branch (the whole cut shifts by one).
    let anchor1 = ForkAnchor {
        user_text_sha256: text_sha256_hex("/aimax:code-review 审查1772"),
        seq_hint: Some(3),
        tail_occurrence: None,
    };
    let cut1 = fork_keep_count(&path, &anchor1, &parsed.messages, &frames).unwrap();
    assert_eq!(cut1, 7, "turn 1 ends at turn 2's line (the image-only turn)");
    assert_eq!(
        parse_first_lines(&bytes, cut1)
            .iter()
            .map(|m| m.text.as_str())
            .collect::<Vec<_>>(),
        [
            "先看一眼仓库结构",
            "仓库不大",
            "/aimax:code-review 审查1772",
            "看过了",
        ],
        "nothing after the skill turn may get in"
    );

    // Turn 2 = the image-only turn: empty text, but a visible user row the extractor accepts,
    // so also a valid cut.
    let anchor2 = ForkAnchor {
        user_text_sha256: text_sha256_hex(""),
        seq_hint: Some(5),
        tail_occurrence: None,
    };
    let cut2 = fork_keep_count(&path, &anchor2, &parsed.messages, &frames).unwrap();
    assert_eq!(cut2, 8, "turn 2 ends at turn 3's line (what can you do)");
    assert_eq!(
        parse_first_lines(&bytes, cut2)
            .iter()
            .map(|m| m.text.as_str())
            .collect::<Vec<_>>(),
        [
            "先看一眼仓库结构",
            "仓库不大",
            "/aimax:code-review 审查1772",
            "看过了",
            "",
        ],
        "the image turn itself stays in the branch (with its empty-text row)"
    );

    // Turn 3 ("what can you do"): cut at turn 4's line; the branch keeps lines 0..9.
    let anchor = ForkAnchor {
        user_text_sha256: text_sha256_hex("你能干啥"),
        seq_hint: Some(6),
        tail_occurrence: None,
    };
    let cut = fork_keep_count(&path, &anchor, &parsed.messages, &frames)
        .expect("the anchor must hit: the text matches the transcript exactly");
    assert_eq!(
        cut, 10,
        "the cut = the next turn's user record line (line 10 from 0 = `one more`), excluded"
    );

    // Semantic assertion: the copied prefix is exactly "turns 0..2 + the anchor turn", nothing more or less.
    assert_eq!(
        parse_first_lines(&bytes, cut)
            .iter()
            .map(|m| m.text.as_str())
            .collect::<Vec<_>>(),
        [
            "先看一眼仓库结构",
            "仓库不大",
            "/aimax:code-review 审查1772",
            "看过了",
            "",
            "你能干啥",
            "啥都能干",
        ],
        "the branch must include the anchor turn (and every turn before it), and nothing after it"
    );

    // Text that doesn't match → None (the caller reports an error, never falling back to "fork from the end").
    let missing = ForkAnchor {
        user_text_sha256: text_sha256_hex("转录本里没有这句话"),
        seq_hint: None,
        tail_occurrence: None,
    };
    assert_eq!(
        fork_keep_count(&path, &missing, &parsed.messages, &frames),
        None
    );

    let _ = std::fs::remove_dir_all(&dir);
}

#[test]
fn claude_fork_cut_keeps_the_whole_file_at_the_last_turn() {
    // The anchor is the last turn: no user record follows, so the cut is `user_row_lines`'s
    // end sentinel (`usize::MAX` = keep the whole file), which includes the clicked turn.
    // The sentinel mustn't make the caller count the lines again (that would make "the whole file" a second
    // source of truth), so this asserts "what copying with this result produces == the source file".
    let session_id = "22222222-2222-4222-8222-222222222222";
    let caveat = "<local-command-caveat>Caveat: local command.</local-command-caveat>";
    let model = "<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args></command-args>";
    let lines = vec![
        claude_user_line(session_id, caveat, true, "2026-10-22T12:00:00.000Z"),
        claude_user_line(session_id, model, false, "2026-10-22T12:00:01.000Z"),
        // 2 the only turn
        claude_user_line(session_id, "你好", false, "2026-10-22T12:00:02.000Z"),
        claude_assistant_line(session_id, "你好", "2026-10-22T12:00:03.000Z"),
        // One more stdout at the end: it makes no user message but does take a line; "the whole
        // file" must carry it too.
        claude_user_line(
            session_id,
            "<local-command-stdout>Set model to Opus</local-command-stdout>",
            false,
            "2026-10-22T12:00:04.000Z",
        ),
    ];
    let bytes = lines.join("\n") + "\n";
    let dir = std::env::temp_dir().join(format!("ccgui-fork-{}", uuid::Uuid::new_v4()));
    std::fs::create_dir_all(&dir).unwrap();
    let path = dir.join(format!("{session_id}.jsonl"));
    std::fs::write(&path, &bytes).unwrap();

    let frames = std::collections::HashSet::new();
    let parsed = crate::engines::history::parse_session_file("claude", &path, &frames).unwrap();
    assert_eq!(
        parsed
            .messages
            .iter()
            .map(|m| m.text.as_str())
            .collect::<Vec<_>>(),
        ["你好", "你好"],
        "fixture premise: the caveat and in-window envelope make no user row; the only turn is on line 2"
    );

    let anchor = ForkAnchor {
        user_text_sha256: text_sha256_hex("你好"),
        seq_hint: Some(1),
        tail_occurrence: None,
    };
    let cut = fork_keep_count(&path, &anchor, &parsed.messages, &frames)
        .expect("the anchor must hit: the text matches the transcript exactly");
    assert_eq!(
        cut,
        usize::MAX,
        "the last turn's cut = the whole file (the end sentinel, not some line number that cuts the tail)"
    );
    // Really copy with the result: the branch file must equal the source byte for byte (the stdout at the
    // end included).
    assert_eq!(
        copy_first_lines(&bytes, cut),
        bytes,
        "the sentinel must copy the whole file (all {} lines)",
        lines.len()
    );
    assert_eq!(
        parse_first_lines(&bytes, cut)
            .iter()
            .map(|m| m.text.as_str())
            .collect::<Vec<_>>(),
        ["你好", "你好"],
        "the branch includes the anchor turn itself"
    );

    let _ = std::fs::remove_dir_all(&dir);
}

